//! The defence table (C101, C106, C68; the build plan, step 9d-A): what
//! the base defence percentile reads beside the item — each base's
//! defence ranges, and each text a local defence stat displays with what
//! it does — as reviewed reference data.
//!
//! The field that reads it, and every rule that decides its answer, is
//! `pseudo.rs`'s (C101; J5, J6, J8, J33–J35). This module holds the data
//! and says what a row means.
//!
//! # As built
//!
//! - **The table is `reference/defences-v1.toml`** beside this crate,
//!   compiled in by `include_str!` and parsed once, on first use
//!   ([`table`]); generated by `tools/defence-table.py` from the owner's
//!   pinned RePoE clone and one committed extract (`SURFACES.md`),
//!   reviewed as a diff at each pull. It is *data* under C106 — what the
//!   game's files state — and the file's header and the script's
//!   docstring carry the rules a reviewer reads. The loader checks what a
//!   reviewer would: the version this build expects, the realms the class
//!   table's, every name and text non-empty, a range's minimum no more
//!   than its maximum, no text twice, a text that adds or increases
//!   displaying one number and naming a defence, the enchant's naming
//!   none. A table that fails is a build defect surfaced as
//!   [`DefenceTableError`] to every caller — no corpus is loaded over it —
//!   never a partial table.
//! - **A base row is an entry of the export, never a name** ([`Base`]): a
//!   name on several rows — Two-Toned Boots, three — is several bases,
//!   which the field tells apart by the defences the item displays. A row
//!   that ranges no defence is kept as the export holds it. Nothing else
//!   of the export is here: no id, no class, no release state.
//! - **A line row is a displayed text** ([`LineRow`]), the template as
//!   the deriver makes it (C90: each number `#`, the sign in the number),
//!   with what the local stat displaying it does ([`Does`]) to which
//!   defences, and whether a global stat displays the same text — a twin
//!   text, which the text alone cannot tell from its twin (J8). The
//!   `reduced` spelling is a row of its own: the same stat below nothing.
//!   A stat id is no part of it (C90: a stat id exists only at the trade
//!   boundary).
//! - **The realms are the class table's**: the two tables are made from
//!   one export, and the loader refuses a file that says otherwise. In a
//!   realm the table does not cover the field has one reason
//!   ([`DefenceTable::unavailable`]), made once, as a total's is.
//! - **The version is on the basis** (C98; C106's clause (c)): `defences`
//!   beside the other tables', so two builds shipping different tables
//!   never label one answer alike.

use std::collections::{BTreeMap, HashMap};
use std::sync::LazyLock;

use serde::{Deserialize, Serialize};

use crate::corpus::REALMS;
use crate::derive::{Part, Unread};

/// The table this build ships, verbatim (the reviewed file).
pub const DEFENCE_TABLE_TOML: &str = include_str!("../reference/defences-v1.toml");

/// The table version this build expects and every basis cites; a file
/// stamped otherwise is a build defect, not a runtime condition.
pub const DEFENCE_TABLE_VERSION: u32 = 1;

/// The hint on a reason the table gives: the table, not the store, is
/// what could change (C93: a hint, never a guarantee).
pub const TABLE_HINT: &str = crate::class::CLASS_HINT;

/// The hint on a reason the item gives: nothing it displays fixes the
/// value, and a refresh displays the same.
pub const ITEM_HINT: &str =
    "a refresh will not help: what the item displays does not fix the value";

/// One of the four defences an item displays, in the game's order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Defence {
    Armour,
    Evasion,
    EnergyShield,
    Ward,
}

impl Defence {
    pub const ALL: [Defence; 4] = [
        Defence::Armour,
        Defence::Evasion,
        Defence::EnergyShield,
        Defence::Ward,
    ];

    /// The property the game displays the defence under.
    pub fn property(self) -> &'static str {
        match self {
            Defence::Armour => "Armour",
            Defence::Evasion => "Evasion Rating",
            Defence::EnergyShield => "Energy Shield",
            Defence::Ward => "Ward",
        }
    }
}

/// What the local stat a text displays does (the module doc).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Does {
    /// Added to the roll, before any increase.
    Add,
    /// An increase, summed with the others.
    Increase,
    /// The same stat as an increase, below nothing.
    Reduce,
    /// The enchant under which quality does not multiply.
    DropQuality,
}

/// One base of the export: the range of each defence it ranges.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Base {
    ranges: BTreeMap<Defence, (i64, i64)>,
}

impl Base {
    /// The defences the base ranges, in the game's order, each with its
    /// minimum and maximum.
    pub fn ranges(&self) -> impl Iterator<Item = (Defence, (i64, i64))> + '_ {
        self.ranges.iter().map(|(d, r)| (*d, *r))
    }

    /// Whether the base ranges the defence.
    pub fn ranged(&self, defence: Defence) -> bool {
        self.ranges.contains_key(&defence)
    }

    /// A base that ranges no defence.
    pub fn is_empty(&self) -> bool {
        self.ranges.is_empty()
    }
}

/// One text a local defence stat displays.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LineRow {
    pub does: Does,
    /// The defences it does it to; none under [`Does::DropQuality`].
    pub to: Vec<Defence>,
    /// A global stat displays the same text.
    pub twin: bool,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct File {
    version: u32,
    realms: Vec<String>,
    source: String,
    #[allow(dead_code)]
    game: String,
    #[allow(dead_code)]
    generated_by: String,
    #[serde(rename = "base", default)]
    bases: Vec<BaseIn>,
    #[serde(rename = "line", default)]
    lines: Vec<LineIn>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct BaseIn {
    name: String,
    armour: Option<(i64, i64)>,
    evasion: Option<(i64, i64)>,
    energy_shield: Option<(i64, i64)>,
    ward: Option<(i64, i64)>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct LineIn {
    text: String,
    does: Does,
    to: Vec<Defence>,
    twin: bool,
}

/// The parsed, checked table. Read-only; one per build.
#[derive(Debug)]
pub struct DefenceTable {
    version: u32,
    realms: Vec<String>,
    source: String,
    /// Each name to the bases of that name, in the file's order.
    bases: HashMap<String, Vec<Base>>,
    rows: usize,
    lines: HashMap<String, LineRow>,
    /// The reason an item of a realm the table does not cover carries,
    /// made once for each realm GGG has, and once for any other.
    unavailable: HashMap<String, Unread>,
    elsewhere: Unread,
}

/// Why a table text is not a table. Every arm names the offending row so
/// a reviewer can fix the file, not the loader.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DefenceTableError {
    Parse(String),
    Version {
        found: u32,
        expected: u32,
    },
    UnknownRealm(String),
    NoRealm,
    /// The class table, made from the same export, does not load or
    /// covers other realms.
    ClassTable(String),
    NoBase,
    NoLine,
    EmptyName,
    /// A range whose minimum is over its maximum.
    Range {
        base: String,
    },
    DuplicateLine(String),
    /// A text whose row does not say what a line of it does: an addition
    /// or an increase that displays other than one number or names no
    /// defence, the enchant naming one.
    Line(String),
}

impl std::fmt::Display for DefenceTableError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            DefenceTableError::Parse(e) => write!(f, "the defence table does not parse: {e}"),
            DefenceTableError::Version { found, expected } => write!(
                f,
                "the defence table is version {found}; this build reads version {expected}"
            ),
            DefenceTableError::UnknownRealm(realm) => {
                write!(f, "the defence table names a realm GGG has not: {realm:?}")
            }
            DefenceTableError::NoRealm => write!(f, "the defence table names no realm"),
            DefenceTableError::ClassTable(e) => write!(
                f,
                "the defence table is not of the class table's realms: {e}"
            ),
            DefenceTableError::NoBase => write!(f, "the defence table has no base"),
            DefenceTableError::NoLine => write!(f, "the defence table has no line"),
            DefenceTableError::EmptyName => {
                write!(f, "the defence table has a base or a line with no name")
            }
            DefenceTableError::Range { base } => write!(
                f,
                "the defence table gives {base:?} a minimum over its maximum"
            ),
            DefenceTableError::DuplicateLine(text) => {
                write!(f, "the defence table lists the text {text:?} twice")
            }
            DefenceTableError::Line(text) => write!(
                f,
                "the defence table does not say what a line of {text:?} does: one number and a defence, or the enchant and none"
            ),
        }
    }
}

impl std::error::Error for DefenceTableError {}

static TABLE: LazyLock<Result<DefenceTable, DefenceTableError>> =
    LazyLock::new(|| DefenceTable::parse(DEFENCE_TABLE_TOML));

/// The shipped table, parsed and checked once.
pub fn table() -> Result<&'static DefenceTable, &'static DefenceTableError> {
    TABLE.as_ref()
}

/// Why the percentile could not be established on an item, this field's
/// part of C93's closed list of reasons: the kind a count tallies. One
/// for each thing that can fail beyond what the deriver says unread (J33:
/// "the reason saying which part failed").
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum PercentileGap {
    /// The item's realm has no table (J35).
    NoTableForRealm,
    /// The item has no base to look up.
    NoBase,
    /// The table holds no base of the item's name.
    BaseNotInTable,
    /// The table holds the name more than once, and the defences the
    /// item displays are those of more than one of its rows.
    BaseHeldMoreThanOnce,
    /// No row of the base has every defence it ranges displayed (J33).
    BaseDefenceNotDisplayed,
    /// A twin text in `implicitMods` of an item neither eldritch nor
    /// synthesised (J8).
    TwinOfNeitherMark,
    /// The same, of an item both (J33).
    TwinOfBothMarks,
    /// A twin text in an array J8 does not name (J33).
    TwinInAnotherArray,
    /// A defence line in `crucibleMods` (J33).
    CrucibleLine,
    /// No integer gives the display.
    NoRoll,
    /// The base's minimum is its maximum (J33).
    MinimumIsMaximum,
    /// Several rolls give the display, at different values (J33).
    SeveralValues,
}

impl PercentileGap {
    /// What was unread, as a reason and a tally name it (`eval::reason`).
    pub fn unread(self) -> &'static str {
        match self {
            PercentileGap::NoTableForRealm => "the percentile: no table for the realm",
            PercentileGap::NoBase => "the percentile: no base",
            PercentileGap::BaseNotInTable => "the percentile: base not in the table",
            PercentileGap::BaseHeldMoreThanOnce => "the percentile: base held more than once",
            PercentileGap::BaseDefenceNotDisplayed => {
                "the percentile: a defence of the base not displayed"
            }
            PercentileGap::TwinOfNeitherMark => {
                "the percentile: an implicit twin on an item of neither mark"
            }
            PercentileGap::TwinOfBothMarks => {
                "the percentile: an implicit twin on an item of both marks"
            }
            PercentileGap::TwinInAnotherArray => {
                "the percentile: a twin text in an array no ruling names"
            }
            PercentileGap::CrucibleLine => "the percentile: a defence line of a crucible node",
            PercentileGap::NoRoll => "the percentile: no roll gives the display",
            PercentileGap::MinimumIsMaximum => "the percentile: the base's minimum is its maximum",
            PercentileGap::SeveralValues => "the percentile: several rolls of different values",
        }
    }

    /// The table's hint where the table is what could change, the item's
    /// where nothing the item displays fixes the value.
    pub fn hint(self) -> &'static str {
        match self {
            PercentileGap::NoTableForRealm | PercentileGap::BaseNotInTable => TABLE_HINT,
            PercentileGap::NoBase
            | PercentileGap::BaseHeldMoreThanOnce
            | PercentileGap::BaseDefenceNotDisplayed
            | PercentileGap::TwinOfNeitherMark
            | PercentileGap::TwinOfBothMarks
            | PercentileGap::TwinInAnotherArray
            | PercentileGap::CrucibleLine
            | PercentileGap::NoRoll
            | PercentileGap::MinimumIsMaximum
            | PercentileGap::SeveralValues => ITEM_HINT,
        }
    }
}

impl DefenceTable {
    /// Parse and check a table text. The shipped file goes through
    /// [`table`]; this is the same path over any text, for the tests
    /// that pin what the loader refuses.
    pub fn parse(text: &str) -> Result<DefenceTable, DefenceTableError> {
        let file: File =
            toml::from_str(text).map_err(|e| DefenceTableError::Parse(e.to_string()))?;
        if file.version != DEFENCE_TABLE_VERSION {
            return Err(DefenceTableError::Version {
                found: file.version,
                expected: DEFENCE_TABLE_VERSION,
            });
        }
        if file.realms.is_empty() {
            return Err(DefenceTableError::NoRealm);
        }
        if let Some(realm) = file.realms.iter().find(|r| !REALMS.contains(&r.as_str())) {
            return Err(DefenceTableError::UnknownRealm(realm.clone()));
        }
        // the realms are the class table's: one export made both
        let classes =
            crate::class::table().map_err(|e| DefenceTableError::ClassTable(e.to_string()))?;
        if file.realms.as_slice() != classes.realms() {
            return Err(DefenceTableError::ClassTable(format!(
                "it covers {}, and classes v{} covers {}",
                file.realms.join(", "),
                classes.version(),
                classes.realms().join(", ")
            )));
        }
        if file.bases.is_empty() {
            return Err(DefenceTableError::NoBase);
        }
        if file.lines.is_empty() {
            return Err(DefenceTableError::NoLine);
        }
        let rows = file.bases.len();
        let mut bases: HashMap<String, Vec<Base>> = HashMap::new();
        for row in file.bases {
            if row.name.is_empty() {
                return Err(DefenceTableError::EmptyName);
            }
            let ranges: BTreeMap<Defence, (i64, i64)> = [
                (Defence::Armour, row.armour),
                (Defence::Evasion, row.evasion),
                (Defence::EnergyShield, row.energy_shield),
                (Defence::Ward, row.ward),
            ]
            .into_iter()
            .filter_map(|(defence, range)| range.map(|range| (defence, range)))
            .collect();
            if ranges.values().any(|(low, high)| low > high) {
                return Err(DefenceTableError::Range { base: row.name });
            }
            bases.entry(row.name).or_default().push(Base { ranges });
        }
        let mut lines: HashMap<String, LineRow> = HashMap::new();
        for row in file.lines {
            if row.text.is_empty() {
                return Err(DefenceTableError::EmptyName);
            }
            let numbers = row.text.matches('#').count();
            let said = match row.does {
                Does::Add | Does::Increase | Does::Reduce => numbers == 1 && !row.to.is_empty(),
                Does::DropQuality => numbers == 0 && row.to.is_empty(),
            };
            if !said {
                return Err(DefenceTableError::Line(row.text));
            }
            if lines.contains_key(&row.text) {
                return Err(DefenceTableError::DuplicateLine(row.text));
            }
            lines.insert(
                row.text,
                LineRow {
                    does: row.does,
                    to: row.to,
                    twin: row.twin,
                },
            );
        }
        let covered = file.realms.join(", ");
        let reason = |realm: &str| Unread {
            part: Part::Percentile(PercentileGap::NoTableForRealm),
            problem: format!(
                "no defence table for realm {realm} (defences v{} covers {covered})",
                file.version
            ),
            line: None,
            name: None,
            socket: None,
        };
        Ok(DefenceTable {
            unavailable: REALMS
                .iter()
                .filter(|r| !file.realms.iter().any(|c| c == *r))
                .map(|r| ((*r).to_string(), reason(r)))
                .collect(),
            elsewhere: reason("outside GGG's"),
            version: file.version,
            realms: file.realms,
            source: file.source,
            bases,
            rows,
            lines,
        })
    }

    pub fn version(&self) -> u32 {
        self.version
    }

    pub fn realms(&self) -> &[String] {
        &self.realms
    }

    /// How many base rows the table holds, a name on several rows each.
    pub fn rows(&self) -> usize {
        self.rows
    }

    /// How many names the base rows are of.
    pub fn names(&self) -> usize {
        self.bases.len()
    }

    /// How many line texts the table holds.
    pub fn texts(&self) -> usize {
        self.lines.len()
    }

    /// The bases of a name, exact, as GGG displays `baseType`: none, one,
    /// or — where the export holds the name on several entries — each.
    pub fn bases(&self, name: &str) -> &[Base] {
        self.bases.get(name).map_or(&[], Vec::as_slice)
    }

    /// What a line of this template does, where a local defence stat
    /// displays it.
    pub fn line(&self, template: &str) -> Option<&LineRow> {
        self.lines.get(template)
    }

    /// Why the percentile is unavailable in a realm: none where the table
    /// covers it, and otherwise the one reason every item of the realm
    /// carries (J35).
    pub fn unavailable(&self, realm: &str) -> Option<&Unread> {
        if self.realms.iter().any(|r| r == realm) {
            return None;
        }
        Some(self.unavailable.get(realm).unwrap_or(&self.elsewhere))
    }

    /// What a definition says of the table as a whole: its version, what
    /// it holds and where it is from (C106's clause (c)).
    pub fn provenance(&self) -> String {
        format!(
            "defences v{}, {} bases of {} names and {} line texts over {}: {}",
            self.version,
            self.rows,
            self.bases.len(),
            self.lines.len(),
            self.realms.join(", "),
            self.source
        )
    }
}

#[cfg(test)]
mod tests {
    use super::{DEFENCE_TABLE_VERSION, Defence, DefenceTable, DefenceTableError, Does, table};

    fn text(rows: &str) -> String {
        format!(
            "version = 1\nrealms = [\"pc\", \"xbox\", \"sony\"]\nsource = \"s\"\ngame = \"g\"\ngenerated_by = \"t\"\n{rows}"
        )
    }

    const ONE: &str = "[[base]]\nname = \"Plate Vest\"\narmour = [19, 27]\n[[line]]\ntext = \"# to Armour\"\ndoes = \"add\"\nto = [\"armour\"]\ntwin = true\n";

    /// The shipped file parses under the loader's checks, is the version
    /// this build cites, and holds what its generator counted: 476 rows
    /// of 474 names, Two-Toned Boots three times, two bases whose minimum
    /// is their maximum, one ranging no defence; 22 texts, 10 of them
    /// twin, the enchant one of the 22.
    #[test]
    fn the_shipped_table_loads_and_holds_what_its_header_counts() {
        let t = table().unwrap();
        assert_eq!(t.version(), DEFENCE_TABLE_VERSION);
        assert_eq!(t.realms(), ["pc", "xbox", "sony"]);
        assert_eq!((t.rows(), t.names(), t.texts()), (476, 474, 22));
        assert_eq!(t.bases("Two-Toned Boots").len(), 3);
        assert_eq!(t.bases("Plate Vest").len(), 1);
        assert_eq!(
            t.bases("Plate Vest")[0].ranges().collect::<Vec<_>>(),
            [(Defence::Armour, (19, 27))]
        );
        assert!(t.bases("Ruby Ring").is_empty());
        let flat: Vec<&String> = t
            .bases
            .iter()
            .filter(|(_, rows)| {
                rows.iter()
                    .any(|b| b.ranges().any(|(_, (low, high))| low == high))
            })
            .map(|(name, _)| name)
            .collect();
        assert_eq!(flat.len(), 2, "{flat:?}");
        assert!(t.bases("Kaom's Plate").len() == 1 && t.bases("Kaom's Greaves").len() == 1);
        let none = t
            .bases
            .values()
            .flatten()
            .filter(|base| base.is_empty())
            .count();
        assert_eq!(none, 1);
        assert_eq!(t.lines.values().filter(|row| row.twin).count(), 10);
        let enchant = t.line("Quality does not increase Defences").unwrap();
        assert_eq!(
            (enchant.does, enchant.to.len(), enchant.twin),
            (Does::DropQuality, 0, false)
        );
        let reduced = t.line("#% reduced Armour").unwrap();
        assert_eq!(
            (reduced.does, reduced.to.as_slice(), reduced.twin),
            (Does::Reduce, [Defence::Armour].as_slice(), true)
        );
        // a twin by its text: the local energy shield increase is none
        assert!(!t.line("#% increased Energy Shield").unwrap().twin);
        assert!(t.line("# to maximum Energy Shield").unwrap().twin);
        assert!(t.line("# to maximum Life").is_none());
        assert!(t.unavailable("pc").is_none());
        assert_eq!(
            t.unavailable("poe2").unwrap().problem,
            "no defence table for realm poe2 (defences v1 covers pc, xbox, sony)"
        );
        assert!(t.provenance().starts_with(
            "defences v1, 476 bases of 474 names and 22 line texts over pc, xbox, sony: RePoE"
        ));
    }

    #[test]
    fn the_loader_refuses_what_a_reviewer_would() {
        assert!(DefenceTable::parse(&text(ONE)).is_ok());
        let refused = |rows: &str| DefenceTable::parse(&text(rows)).unwrap_err();
        assert_eq!(
            DefenceTable::parse(&text(ONE).replacen("version = 1", "version = 2", 1)).unwrap_err(),
            DefenceTableError::Version {
                found: 2,
                expected: 1
            }
        );
        assert!(matches!(
            DefenceTable::parse(&text(ONE).replacen("\"pc\", ", "", 1)).unwrap_err(),
            DefenceTableError::ClassTable(_)
        ));
        assert_eq!(
            DefenceTable::parse(&text(ONE).replacen("\"pc\"", "\"ps9\"", 1)).unwrap_err(),
            DefenceTableError::UnknownRealm("ps9".to_string())
        );
        assert_eq!(
            refused(&ONE.replacen("[19, 27]", "[27, 19]", 1)),
            DefenceTableError::Range {
                base: "Plate Vest".to_string()
            }
        );
        assert_eq!(
            refused(&ONE.replacen("\"Plate Vest\"", "\"\"", 1)),
            DefenceTableError::EmptyName
        );
        assert_eq!(
            refused(&format!(
                "{ONE}[[line]]\ntext = \"# to Armour\"\ndoes = \"add\"\nto = [\"armour\"]\ntwin = false\n"
            )),
            DefenceTableError::DuplicateLine("# to Armour".to_string())
        );
        // a row that does not say what a line of it does
        for line in [
            "text = \"# to # Armour\"\ndoes = \"add\"\nto = [\"armour\"]\ntwin = false\n",
            "text = \"#% increased Armour\"\ndoes = \"increase\"\nto = []\ntwin = false\n",
            "text = \"Quality does nothing\"\ndoes = \"drop_quality\"\nto = [\"ward\"]\ntwin = false\n",
        ] {
            assert!(
                matches!(
                    refused(&format!("{ONE}[[line]]\n{line}")),
                    DefenceTableError::Line(_)
                ),
                "{line}"
            );
        }
        assert!(matches!(
            refused(&ONE.replacen("armour = [19, 27]", "block = 24", 1)),
            DefenceTableError::Parse(_)
        ));
        assert_eq!(
            refused("[[base]]\nname = \"Plate Vest\"\n"),
            DefenceTableError::NoLine
        );
        assert_eq!(
            refused(
                "[[line]]\ntext = \"# to Armour\"\ndoes = \"add\"\nto = [\"armour\"]\ntwin = true\n"
            ),
            DefenceTableError::NoBase
        );
    }
}
