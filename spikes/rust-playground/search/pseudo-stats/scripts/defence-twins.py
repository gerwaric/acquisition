#!/usr/bin/env python3
"""Open question 9: can a private item tell a defence line's global twin from
the local line? Writes ../data/defence-twins.csv and prints the counts.

    defence-twins.py

A twin text is one a local defence stat (percentile.py's ROLES) and a global
stat both display: the trade site's texts (search/repoe/data/trade-stat-map.csv)
with `(Local)` dropped, the `reduced` spelling beside each `increased` one.
A private item shows the text alone; the site's id says which stat it is.

Over the captures (data/captures.json, every distinct item showing a defence),
each line of a twin text: the side its id gives (local or global), and the
facts a private body also carries — the array, the line's flags, the item's
rarity, frame, base and class, whether it is a unique, the line's position in
its array and the lines beside it, whether the item shows the line's defence
type, and the item's own marks (every top-level key whose value is true, and
its influences). The extract keeps no item-level marks, so these are read
from the fetch they came from (raw/searches/<search>-fetch*.json, local only;
the n-th item of a search's pages is the extract's n-th, checked by base) and
only the key names leave raw/. Beside them, what the export's mods say of the
line by its text (the join of ranged-census.py, by the line's array: every
mod of the generation types that array is made from with a row of the line's
text whose ranges hold its numbers; of each, the stats the export translates
to that text and their `is_local`): local, global, both, or none found.

Over the copy (search/item-facts/raw/m3/store/mock/GERWARIC_7694.db, opened
read-only), every live item showing a defence, each line of a twin text: the
same facts and the same join; the side is unknown there.

A fact separates when no value of it is held by a global twin and a local line
both, over the captures; each such fact is a candidate, printed with the items
it rests on, and counted over the copy: how many items it would call global.
"""

import csv
import importlib.util
import json
import re
import sqlite3
import sys
import tomllib
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("percentile_shapes", HERE / "percentile-shapes.py")
S = importlib.util.module_from_spec(spec)
spec.loader.exec_module(S)
P = S.P

TRACK = P.TRACK
SEARCH = P.SEARCH
ROOT = SEARCH.parent
RAW = TRACK / "raw" / "searches"
OUT = TRACK / "data" / "defence-twins.csv"
POE1 = P.CLONES / "poe1" / "data"
FIRST_LINE = ("# generated by scripts/defence-twins.py from data/captures.json, raw/searches/*-fetch*.json "
              "(item marks only), ../item-facts/raw/m3/store/mock/GERWARIC_7694.db (read-only), "
              "crates/acquisition-search/reference/classes-v1.toml, ../repoe/data/trade-stat-map.csv and "
              "poe1/data/mods.json, stats.json, stat_translations.json @ e2bd511a")

NUM = re.compile(r"(?<![\d#])[-+]?\d+(?:\.\d+)?")
MARKUP = re.compile(r"\[([^\[\]|]*)(?:\|([^\[\]]*))?\]")
RANGE = re.compile(r"\((-?\d+(?:\.\d+)?)-(-?\d+(?:\.\d+)?)\)|(-?\d+(?:\.\d+)?)")
PLACEHOLDER = re.compile(r"\{\d+(?::[^}]*)?\}")
# The generation types each array is made from (ranged-census.py's, widened to
# every rarity: a rare's explicit is a prefix or a suffix, an implicit may be
# the base's, an eldritch one, a corruption's or a synthesis's).
GENERATION = {
    "explicitMods": ("prefix", "suffix", "unique", "essence"),
    "implicitMods": ("unique", "eater_of_worlds_implicit", "searing_exarch_implicit", "corrupted",
                     "synthesis_a", "synthesis_globals", "synthesis_bonus"),
    "enchantMods": ("enchantment",),
    "scourgeMods": ("scourge_benefit", "scourge_detriment"),
    "crucibleMods": ("crucible_tree", "crucible_unique_tree"),
}
TYPE_OF = [("Energy Shield", "es"), ("Evasion", "ev"), ("Armour", "ar"), ("Ward", "ward")]
FACTS = ["array", "flags", "rarity", "frame", "unique", "class", "base", "position", "beside",
         "type_shown", "marks", "export_says"]
SEPARATORS = ["array", "flags", "rarity", "frame", "unique", "class", "base", "position", "type_shown",
              "marks", "export_says", "array+marks", "array+export_says"]


def template(text):
    return NUM.sub("#", MARKUP.sub(lambda m: m.group(2) or m.group(1), text))


def numbers(text):
    return [float(n) for n in NUM.findall(text)]


def twin_texts():
    """(the twin templates, {trade id: 'local' | 'global'} for the ids displaying one)."""
    local_stats = set(P.ROLES)
    rows = [row for _, row in P.read_commented_csv(P.TRADE_MAP)]
    shown = lambda row: re.sub(r" \(Local\)$", "", row["trade_text"]).replace("+#", "#")
    local_t = {shown(r) for r in rows if r["repoe_ids"] in local_stats}
    global_t = {shown(r) for r in rows if r["repoe_ids"] not in local_stats
                and not r["trade_text"].endswith(" (Local)")}
    twins = local_t & global_t
    twins |= {t.replace("increased", "reduced") for t in twins if "increased" in t}
    side = {}
    for r in rows:
        t = shown(r)
        if t.replace("reduced", "increased") in twins or t in twins:
            side[r["trade_id"]] = "local" if r["repoe_ids"] in local_stats else "global"
    return twins, side


def export_join(twins):
    """{(generation type, template): [(mod id, spans, {is_local of the stats behind})]}"""
    stats = json.loads((POE1 / "stats.json").read_text())
    renders = defaultdict(set)
    for entry in json.loads((POE1 / "stat_translations.json").read_text()):
        for s in entry.get("English", []):
            t = PLACEHOLDER.sub("#", s["string"]).replace("+#", "#")
            if t in twins:
                renders[t].update(entry["ids"])
    by_row = defaultdict(list)
    for mod_id, mod in json.loads((POE1 / "mods.json").read_text()).items():
        for row in (mod.get("text") or "").split("\n"):
            spans = []

            def one(m):
                if m.group(3) is not None:
                    v = float(m.group(3))
                    spans.append((v, v))
                else:
                    spans.append((float(m.group(1)), float(m.group(2))))
                return "#"
            t = RANGE.sub(one, row).replace("+#", "#")
            if t not in twins:
                continue
            behind = [s["id"] for s in mod["stats"] if s["id"] in renders[t]]
            flags = {bool(stats.get(s, {}).get("is_local")) for s in behind}
            by_row[(mod["generation_type"], t)].append((mod_id, spans, flags))
    return by_row


def by_generation(by_row, array, t, row):
    """The generation types whose mods hold the line, each with what their stats say."""
    nums = [abs(n) for n in numbers(row)]
    out = defaultdict(set)
    for g in GENERATION.get(array, ()):
        for _, spans, f in by_row[(g, t)]:
            if len(spans) >= len(nums) and all(lo <= n <= hi for n, (lo, hi) in zip(nums, spans)):
                out[g] |= {"local" if x else "global" for x in f} or {"no stat"}
    return ";".join(f"{g}:{'+'.join(sorted(v))}" for g, v in sorted(out.items())) or "-"


def says(by_row, array, t, row):
    if array not in GENERATION:
        return "none: no generation type for the array"
    nums = [abs(n) for n in numbers(row)]
    found = [f for g in GENERATION[array] for _, spans, f in by_row[(g, t)]
             if len(spans) >= len(nums) and all(lo <= n <= hi for n, (lo, hi) in zip(nums, spans))]
    flags = set().union(*found) if found else set()
    if not found:
        return "none: no mod's text holds the line at its numbers"
    if flags == {True}:
        return "local"
    if flags == {False}:
        return "global"
    if not flags:
        return "none: the mods found carry no stat the export translates to the text"
    return "both"


def type_of(t):
    return next(code for word, code in TYPE_OF if word in t)


def marks_of(raw):
    keys = sorted(k for k, v in raw.items() if v is True and k not in ("identified", "verified"))
    keys += sorted(f"influence:{k}" for k, v in (raw.get("influences") or {}).items() if v)
    return ";".join(keys) or "-"


def facts(source, locator, base, rarity, frame, classes, arrays, shown, marks, twins, by_row):
    """One row per twin line of an item: its facts, side left to the caller."""
    out = []
    for array, lines in arrays.items():
        if array == "pseudoMods":
            continue
        rows = [(l, row) for l in lines for row in (l.get("description") or "").split("\n")]
        temps = [template(row) for _, row in rows]
        for k, (line, row) in enumerate(rows):
            t = temps[k]
            if t not in twins:
                continue
            flags = ";".join(sorted(f for f, v in (line.get("flags") or {}).items() if v)) or "-"
            beside = " | ".join(temps[j] for j in (k - 1, k + 1) if 0 <= j < len(temps))
            out.append({
                "source": source, "locator": locator, "line": row, "template": t, "hash": line.get("hash", ""),
                "array": array, "flags": flags, "rarity": rarity or "", "frame": str(frame),
                "unique": "yes" if rarity == "Unique" else "no",
                "class": "|".join(sorted(classes.get(base, set()))) or "not in the class table",
                "base": base, "position": f"{k + 1} of {len(rows)}", "beside": beside or "-",
                "type_shown": "yes" if type_of(t) in shown else "no", "marks": marks,
                "export_says": says(by_row, array, t, row).split(":")[0],
                "export_by_generation": by_generation(by_row, array, t, row),
            })
    return out


def main():
    twins, side_of = twin_texts()
    by_row = export_join(twins)
    classes = defaultdict(set)
    for c in tomllib.loads(S.CLASSES.read_text())["class"]:
        for b in c["bases"]:
            classes[b].add(c["name"])

    rows = []
    seen = set()
    captures = json.loads(P.CAPTURES.read_text())["searches"]
    for name, capture in captures.items():
        raw_items = []
        for fetch in [RAW / f"{name}-fetch.json"] + sorted(
                RAW.glob(f"{name}-fetch-*.json"), key=lambda p: int(p.stem.rsplit("-", 1)[1])):
            if fetch.exists() and fetch.stat().st_size:
                raw_items += [r["item"] for r in json.loads(fetch.read_text())["result"]]
        for i, item in enumerate(capture["fetched"] or []):
            shown = {P.PROPERTY[p[1]] for p in item.get("properties", []) if p[1] in P.PROPERTY}
            if not shown:
                continue
            key = json.dumps({k: (dict(v, pseudoMods=None) if k == "lines" else v)
                              for k, v in item.items() if k != "extended"}, sort_keys=True)
            if key in seen:
                continue
            seen.add(key)
            raw = raw_items[i] if i < len(raw_items) else None
            if raw is None or raw.get("baseType") != item.get("baseType"):
                sys.exit(f"{name}[{i}]: the fetch does not hold the extract's item at its place")
            for r in facts("captures", f"{name}[{i}]", item.get("baseType") or item["typeLine"], item["rarity"],
                           item.get("frameType"), classes, item["lines"], shown, marks_of(raw), twins, by_row):
                r["site_says"] = side_of.get(r["hash"].removeprefix("stat."), "not a twin id")
                rows.append(r)

    db = sqlite3.connect(f"file:{S.STORE}?mode=ro", uri=True)
    copy_items = 0
    for item_id, realm, rarity, body in db.execute(
            "select id, realm, rarity, json from items where removed_at is null order by id"):
        body = json.loads(body)
        props = S.store_properties(body)
        shown = S.shown_defences(props)
        if not shown:
            continue
        copy_items += 1
        arrays = {a: [e if isinstance(e, dict) else {"description": e} for e in v]
                  for a, v in body.items() if a.endswith("Mods") and isinstance(v, list)}
        base = body.get("baseType") or body.get("typeLine") or ""
        for r in facts("copy", f"item {item_id}", base, rarity, body.get("frameType"), classes, arrays, shown,
                       marks_of(body), twins, by_row):
            r["site_says"] = f"unknown ({realm})"
            rows.append(r)

    for r in rows:
        r["array+marks"] = f"{r['array']} / {r['marks']}"
        r["array+export_says"] = f"{r['array']} / {r['export_says']}"
    header = ["source", "locator", "line", "site_says"] + FACTS + ["export_by_generation", "template"]
    with OUT.open("w", newline="") as fh:
        fh.write(FIRST_LINE + "\n")
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        for r in rows:
            w.writerow([r[h] for h in header])

    cap = [r for r in rows if r["source"] == "captures" and r["site_says"] in ("local", "global")]
    copy = [r for r in rows if r["source"] == "copy"]
    print(f"twin texts: {len(twins)}: " + "; ".join(sorted(twins)))
    items = lambda rs: len({r["locator"] for r in rs})
    for s in ("global", "local"):
        mine = [r for r in cap if r["site_says"] == s]
        print(f"captures, {s} twin lines: {len(mine)} on {items(mine)} items; of a type the item shows: "
              f"{sum(1 for r in mine if r['type_shown'] == 'yes')} lines on "
              f"{items([r for r in mine if r['type_shown'] == 'yes'])} items")
    print(f"copy: {copy_items} live items show a defence; {len(copy)} twin lines on {items(copy)} of them; "
          f"of a type the item shows: {sum(1 for r in copy if r['type_shown'] == 'yes')} lines on "
          f"{items([r for r in copy if r['type_shown'] == 'yes'])} items")
    print("each fact over the captures (value: global lines/items, local lines/items); "
          "a fact separates when no value is held by both:")
    candidates = []
    for fact in SEPARATORS:
        by = defaultdict(lambda: {"global": [], "local": []})
        for r in cap:
            by[r[fact]][r["site_says"]].append(r)
        mixed = [v for v, d in by.items() if d["global"] and d["local"]]
        print(f"  {fact}: {'separates' if not mixed else f'does not ({len(mixed)} values on both sides)'}")
        if fact in ("base", "beside", "position", "class") and mixed:
            continue
        for v, d in sorted(by.items(), key=lambda kv: (-len(kv[1]["global"]), kv[0])):
            print(f"      {v}: global {len(d['global'])}/{items(d['global'])}, "
                  f"local {len(d['local'])}/{items(d['local'])}")
        if not mixed:
            candidates.append((fact, {v for v, d in by.items() if d["global"]}))
    print("each separating fact over the copy: the twin lines and items it calls global "
          "(of a type the item shows), and the values the captures never saw:")
    for fact, global_values in candidates:
        called = [r for r in copy if r[fact] in global_values]
        seen_values = {r[fact] for r in cap}
        unseen = [r for r in copy if r[fact] not in seen_values]
        shown_called = [r for r in called if r["type_shown"] == "yes"]
        print(f"  {fact}: {len(called)} lines on {items(called)} items ({len(shown_called)} lines on "
              f"{items(shown_called)} items); a value the captures never saw: {len(unseen)} lines on "
              f"{items(unseen)} items")
    print("every twin line outside explicitMods, by source, site, item marks and the export's word "
          "by generation type (lines/items):")
    other = Counter((r["source"], r["site_says"], r["array"], r["rarity"], r["marks"], r["export_by_generation"])
                    for r in rows if r["array"] != "explicitMods")
    for key, n in sorted(other.items()):
        rs = [r for r in rows if (r["source"], r["site_says"], r["array"], r["rarity"], r["marks"],
                                  r["export_by_generation"]) == key]
        print(f"  {' / '.join(key)}: {n}/{items(rs)}")
    print("the export's word over the copy, by array (lines/items):")
    for (a, e), n in sorted(Counter((r["array"], r["export_says"]) for r in copy).items()):
        rs = [r for r in copy if r["array"] == a and r["export_says"] == e]
        print(f"  {a} / {e}: {n}/{items(rs)}")
    print("the export's mods of a twin text by generation type, rows by what their stats say "
          "(eldritch, synthesis and corruption implicits):")
    for g in ("eater_of_worlds_implicit", "searing_exarch_implicit", "synthesis_a", "synthesis_globals",
              "synthesis_bonus", "corrupted"):
        said = Counter("+".join(sorted("local" if x else "global" for x in f)) or "no stat"
                       for (gen, _), ms in by_row.items() if gen == g for _, _, f in ms)
        print(f"  {g}: " + (", ".join(f"{k} {n}" for k, n in sorted(said.items())) or "none"))
    synth = [r for r in copy if r["array"] == "implicitMods" and "synthesised" in r["marks"].split(";")]
    eld = [r for r in copy if r["array"] == "implicitMods" and {"searing", "tangled"} & set(r["marks"].split(";"))]
    print(f"the copy's implicit twin lines: on an eldritch item (searing or tangled) {len(eld)} on {items(eld)} "
          f"items ({', '.join(sorted({r['base'] for r in eld}))}); on a synthesised item {len(synth)} on "
          f"{items(synth)} items, none held by a synthesis mod")
    print("the copy's twin lines the export says global, each:")
    for r in copy:
        if r["export_says"] == "global":
            print(f"  {r['rarity']} {r['base']} ({r['class']}), {r['array']}: {r['line']}; "
                  f"{r['export_by_generation']}")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
