#!/usr/bin/env python3
"""category, round k read: every name of the site's monster list against Yellow Beast.

    python3 search/category/scripts/round-k-read.py

Reads search/pseudo-stats/data/captures.json (the committed, scrubbed extract) for round k: each
search's total and its fetched items' base types. The extract holds all this run needs; no raw
capture is read. Writes, in data/:

  round-k-read.csv   one row per name of the site's `monster` list (../trade-query/data/
                     items-2026-09-12.json): its search, the total, whether the site listed it under
                     Yellow Beast (yellow by the site's own word, the capture cited), the fetched
                     items' base types, the copy's items, and what the mod-count regularity predicted
                     (data/round-k.csv) — held against the answer, never read as it.
  round-l-read.csv   one row per search of round l (each name round k did not find, under Red
                     Beast): the total, found or not, the fetched base types, its round k pair, the
                     copy's items and the regularity's prediction.
  beast-colours.csv  the table candidate: name, colour — `yellow` found under Yellow Beast (round k),
                     `red` found under Red Beast (round l), `unknown` found under neither — and the
                     search or searches that evidence it.

It checks round l (tools/trade-sheet.py's `round_l`) against the `unknown` names and names any of
its rows whose query an earlier row already asked. It prints the four rows of round k whose query is one of round j's, each beside that row's
answer, and every name where the regularity disagrees with the site. It fails when a search
found items whose base type is not its own name, or when a name has no captured search.
"""

import base64
import collections
import csv
import json
import os
import re
import sys
import zlib

sys.dont_write_bytecode = True  # nothing is cached beside a script this track does not own
import common  # noqa: E402

PS = os.path.join(common.SEARCH, "pseudo-stats")
EXTRACT = os.path.join(PS, "data", "captures.json")
SHEET = os.path.join(PS, "data", "search-sheet.csv")
HEADER = ("# generated by scripts/round-k-read.py from ../pseudo-stats/data/captures.json (rounds j, k and l), "
          "../pseudo-stats/data/search-sheet.csv (rounds j, k, l), data/round-k.csv, ../trade-query/data/items-2026-09-12.json")


def decode(link):
    token = link.rsplit("/", 1)[1]
    return json.loads(zlib.decompress(base64.urlsafe_b64decode(token + "=" * (-len(token) % 4)), 16 + zlib.MAX_WBITS))


def main():
    captures = json.load(open(EXTRACT))["searches"]
    with open(SHEET, newline="") as fh:
        sheet = list(csv.DictReader(fh))
    with open(os.path.join(common.DATA, "round-k.csv"), newline="") as fh:
        predicted = {r["search"]: r for r in csv.DictReader(fh.readlines()[1:])}
    coarse, _ = common.site_coarse()
    site = sorted(n for n, cs in coarse.items() if "monster" in cs)
    by_type = {}
    for r in sheet:
        if re.fullmatch(r"k\d+", r["search"]):
            t = decode(r["link"]).get("type")
            if t:
                by_type[t] = r["search"]
    faults = 0
    rows, colours = [], []
    for name in site:
        k = by_type.get(name)
        c = captures.get(k) if k else None
        if c is None:
            faults += 1
            print(f"FAULT  {name!r}: no captured search")
            continue
        total = c["search"]["total"]
        bases = collections.Counter(i["baseType"] for i in c.get("fetched") or [])
        if set(bases) - {name}:
            faults += 1
            print(f"FAULT  {k}: fetched {dict(bases)} under the name {name!r}")
        found = total > 0
        p = predicted[k]
        rows.append([name, k, total, "yes" if c["search"].get("inexact") else "no", "yes" if found else "no",
                     "; ".join(f"{b}:{n}" for b, n in bases.items()), p["copy_items"], p["mod_count_regularity"]])
        colours.append([name, "yellow" if found else "unknown", k])
    order = {r["search"]: i for i, r in enumerate(sheet)}
    rows.sort(key=lambda r: order[r[1]])
    colours.sort(key=lambda r: order[r[2]])
    # round l: each name round k did not find, under Red Beast
    l_type = {}
    for r in sheet:
        if re.fullmatch(r"l\d+", r["search"]):
            l_type[decode(r["link"]).get("type")] = r["search"]
    l_rows = []
    regularity = {r[0]: (r[6], r[7]) for r in rows}
    for c in colours:
        if c[1] != "unknown":
            continue
        name, k = c[0], c[2]
        ln = l_type.get(name)
        cap = captures.get(ln) if ln else None
        if cap is None:
            if l_type:
                faults += 1
                print(f"FAULT  {name!r}: no captured round l search")
            continue
        total = cap["search"]["total"]
        bases = collections.Counter(i["baseType"] for i in cap.get("fetched") or [])
        if set(bases) - {name}:
            faults += 1
            print(f"FAULT  {ln}: fetched {dict(bases)} under the name {name!r}")
        l_rows.append([name, ln, total, "yes" if cap["search"].get("inexact") else "no", "yes" if total > 0 else "no",
                       "; ".join(f"{b}:{n}" for b, n in bases.items()), k, *regularity[name]])
        c[1], c[2] = ("red", ln) if total > 0 else ("unknown", f"{k} {ln}")
    if l_rows:
        common.write_csv("round-l-read.csv", HEADER, ["name", "search", "total", "inexact", "found_under_red",
                                                     "fetched_base_types", "pair", "copy_items", "mod_count_regularity"], l_rows)
    common.write_csv("round-k-read.csv", HEADER, ["name", "search", "total", "inexact", "found_under_yellow",
                                                 "fetched_base_types", "copy_items", "mod_count_regularity"], rows)
    common.write_csv("beast-colours.csv", HEADER, ["name", "colour", "evidence"], colours)
    if l_rows:
        tally = collections.Counter(c[1] for c in colours)
        print(f"the colour table: {dict(sorted(tally.items()))} of {len(colours)} names")
        for colour in ("yellow", "red", "unknown"):
            held = [c[0] for c in colours if c[1] == colour and regularity[c[0]][0] not in ("", "0")]
            print(f"  the copy's bases {colour}: {len(held)} {held if colour != 'yellow' else ''}")
        dis = [(c[0], regularity[c[0]][1], c[1]) for c in colours if regularity[c[0]][0] not in ("", "0")
               and regularity[c[0]][1] != c[1]]
        print(f"  the regularity against the table, names with items on the copy, disagreeing: {dis or 'none'}")
        print(f"  unknown (found under neither leaf): {[c[0] for c in colours if c[1] == 'unknown']}")
    found = [r for r in rows if r[4] == "yes"]
    print(f"round k beasts: {len(rows)} names; under Yellow Beast found {len(found)}, not found {len(rows) - len(found)}")
    print(f"  not found, the copy's bases first: {[r[0] for r in rows if r[4] == 'no' and r[6] not in ('', '0')]}")
    tab = collections.Counter((r[7], r[4]) for r in rows)
    print(f"  regularity x found under Yellow: {dict(sorted(tab.items()))}")
    disagree = [(r[0], r[1], r[7], "found" if r[4] == "yes" else "not found") for r in rows
                if (r[7] == "yellow" and r[4] == "no") or (r[7] == "red" and r[4] == "yes") or r[7] == "both"]
    print(f"  the regularity against the site, disagreeing: {disagree or 'none'}")
    # round k's rows whose query is one of round j's
    by_query = collections.defaultdict(list)
    for r in sheet:
        by_query[r["query"]].append(r["search"])
    for q, names in by_query.items():
        for ll in [n for n in names if n.startswith("l")]:
            for jj in [n for n in names if n.startswith("j")]:
                print(f"  re-asked: {ll} is {jj}'s query; {ll} {captures.get(ll, {}).get('search', {}).get('total')}, "
                      f"{jj} {captures.get(jj, {}).get('search', {}).get('total')}")
        ks = [n for n in names if n.startswith("k")]
        js = [n for n in names if n.startswith("j")]
        for kk in ks:
            for jj in js:
                kt, jt = captures.get(kk, {}).get("search", {}).get("total"), captures.get(jj, {}).get("search", {}).get("total")
                print(f"  re-asked: {kk} is {jj}'s query; {kk} {kt}, {jj} {jt}")
    # round l, the second pass, against this read and the sheet
    l_rows = [r for r in sheet if re.fullmatch(r"l\d+", r["search"])]
    if l_rows:
        asked = [(decode(r["link"]).get("type"), decode(r["link"])["filters"]["type_filters"]["filters"]["category"]["option"],
                  re.search(r"k\d{3}", r["control"]).group(0)) for r in l_rows]
        want = [(r[0], "monster.redbeast", r[1]) for r in rows if r[4] == "no"]
        if asked != want:
            faults += 1
            print("FAULT  round l is not every unknown name under monster.redbeast, in round k's order, each with its pair")
        repeats = [(r["search"], [n for n in by_query[r["query"]] if n != r["search"]]) for r in l_rows
                   if len(by_query[r["query"]]) > 1]
        print(f"round l: {len(l_rows)} searches, {-(-len(l_rows) // 25)} pages of 25, {len(l_rows) * 10 // 60} min "
              f"{len(l_rows) * 10 % 60} s at one link every 10 s; repeating an earlier row's query: {repeats or 'none'}")
    print(f"faults: {faults}")
    return 1 if faults else 0


if __name__ == "__main__":
    sys.exit(main())
