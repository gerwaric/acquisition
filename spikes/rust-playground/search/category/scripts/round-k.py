#!/usr/bin/env python3
"""category, round k: the sheet's k rows read back, each beast name held against the copy.

    python3 search/category/scripts/round-k.py

Round k is tools/trade-sheet.py's `round_k`, written into search/pseudo-stats/data/search-sheet.csv.
For each k row this script decodes the link and records the category and type, the copy's items
of that base, and what the mod-count regularity of data/round-j-beasts.csv would say of it: yellow
when every copy item of the base carries exactly one of the export's bestiary mods, red when none
does, both when the copy's items differ, no item on the copy otherwise. That column is recorded so
that the sitting's answer can be held against it afterwards; it is never the answer, and no reading
is adopted here (the owner's).

It fails when a name of the site's `monster` list has no search or more than one, when a beast row
is not under `monster.yellowbeast`, when the copy's bases do not come first in beasts.csv's order,
or when the J8 pair (k001, k002) does not name its control.

Inputs (read-only): the sheet, data/beasts.csv, ../trade-query/data/items-2026-09-12.json, the copy
(sqlite mode=ro), poe1/data @ e2bd511a (mods). Output (data/): round-k.csv, one row per search.
"""

import base64
import collections
import csv
import json
import os
import re
import sys
import zlib

sys.dont_write_bytecode = True  # nothing is cached beside a script this track does not own
import common  # noqa: E402

SHEET = os.path.join(common.SEARCH, "pseudo-stats", "data", "search-sheet.csv")
HEADER = ("# generated by scripts/round-k.py from ../pseudo-stats/data/search-sheet.csv (round k), data/beasts.csv, "
          "../trade-query/data/items-2026-09-12.json, the copy ../item-facts/raw/m3 (local), poe1/data @ e2bd511a (mods)")
PACE = 10  # seconds a link: tools/trade-pages.py's PACE
PAGE = 25  # links a page: tools/trade-pages.py's SIZE


def decode(link):
    token = link.rsplit("/", 1)[1]
    return json.loads(zlib.decompress(base64.urlsafe_b64decode(token + "=" * (-len(token) % 4)), 16 + zlib.MAX_WBITS))


def main():
    with open(SHEET, newline="") as fh:
        sheet = [r for r in csv.DictReader(fh) if re.fullmatch(r"k\d+", r["search"])]
    with open(os.path.join(common.DATA, "beasts.csv"), newline="") as fh:
        copy_bases = [r[0] for r in list(csv.reader(fh))[2:]]
    coarse, _ = common.site_coarse()
    site = sorted(n for n, cs in coarse.items() if "monster" in cs)
    ex = common.Export()
    bestiary = {m["name"] for m in ex.mods.values() if m.get("generation_type") == "bestiary" and m.get("name")}
    counts = collections.defaultdict(collections.Counter)
    for _, _, _, b in common.copy_items() or []:
        if common.is_beast(b):
            n = sum(1 for m in b.get("explicitMods") or [] if (m.get("description") or "") in bestiary)
            counts[common.shown(b["baseType"])][n] += 1
    faults = 0
    rows, beast_types = [], []
    for r in sheet:
        q = decode(r["link"])
        cat = (((q.get("filters") or {}).get("type_filters") or {}).get("filters") or {}).get("category", {}).get("option", "")
        typ = q.get("type", "")
        if typ:
            beast_types.append(typ)
            if cat != "monster.yellowbeast":
                faults += 1
                print(f"FAULT  {r['search']}: {typ!r} is under {cat}, not monster.yellowbeast")
            c = counts.get(typ)
            if not c:
                regularity = "no item on the copy"
            else:
                kinds = {"yellow" if n == 1 else "red" for n in c}
                regularity = kinds.pop() if len(kinds) == 1 else "both"
            mods = "; ".join(f"{n}:{v}" for n, v in sorted(c.items())) if c else ""
            items = sum(c.values()) if c else 0
        else:
            regularity, mods, items = "", "", ""
            if not re.search(r"\b[a-z]\d{2,3}\b", r["control"]):
                faults += 1
                print(f"FAULT  {r['search']}: the J8 row names no control")
        rows.append([r["search"], cat, typ or "(none)", items, mods, regularity])
    counted = collections.Counter(beast_types)
    missing = sorted(set(site) - set(counted))
    twice = sorted(n for n, v in counted.items() if v > 1)
    extra = sorted(set(counted) - set(site))
    if missing or twice or extra:
        faults += 1
        print(f"FAULT  names of the site's monster list without a search {missing}, with several {twice}, not on it {extra}")
    if beast_types[: len(copy_bases)] != copy_bases:
        faults += 1
        print("FAULT  the copy's bases do not come first in beasts.csv's order")
    if beast_types[len(copy_bases):] != sorted(beast_types[len(copy_bases):]):
        faults += 1
        print("FAULT  the rest are not in order by name")
    common.write_csv("round-k.csv", HEADER, ["search", "category", "type", "copy_items", "copy_bestiary_mod_counts",
                                            "mod_count_regularity"], rows)
    reg = collections.Counter(r[5] for r in rows if r[5])
    print(f"round k: {len(rows)} searches ({len(rows) - len(beast_types)} J8, {len(beast_types)} beast names); "
          f"the site's monster list {len(site)} names, the copy's bases {len(copy_bases)}")
    print(f"round k: pages of {PAGE}: {-(-len(rows) // PAGE)}; at one link every {PACE} s: "
          f"{len(rows) * PACE // 3600} h {len(rows) * PACE % 3600 // 60} min {len(rows) * PACE % 60} s; "
          f"the copy's bases are {rows[2][0]}–{rows[1 + len(copy_bases)][0]}, the rest {rows[2 + len(copy_bases)][0]}–{rows[-1][0]}")
    print(f"round k: the mod-count regularity over the beast names: {dict(sorted(reg.items()))}")
    print(f"faults: {faults}")
    return 1 if faults else 0


if __name__ == "__main__":
    sys.exit(main())
