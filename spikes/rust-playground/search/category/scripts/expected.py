def natural(name):
    m = re.fullmatch(r"([A-Za-z]+)(\d+)([a-z]*)", name)
    return (m.group(1), int(m.group(2)), m.group(3)) if m else (name, 0, "")


def join(names):
    return " ".join(sorted(set(names), key=natural))


