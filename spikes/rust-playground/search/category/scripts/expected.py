def render(ctx, a):
    und = collections.defaultdict(list)
    for i in a.undecided(ctx):
        und[a.of(i)[1]].append(i)
    if a.all_open and a.all_open[0] == "undecided":
        beast_too = all(a.of(i)[0] == "undecided" for i in MONSTER)
        und = {a.all_open[1]: ["every id" if beast_too else "every id but the three monster.* leaves"]}
    unr = collections.defaultdict(list)
    for i in a.unruled(ctx):
        unr[a.of(i)[1]].append(i)
    if a.all_open and a.all_open[0] == "unruled":
        unr[a.all_open[1]] = ["the class, and every other id but the three monster.* leaves"]
    return (" ".join(a.yes(ctx)), "; ".join(f"{' '.join(v)}: {k}" for k, v in und.items()),
            "; ".join(f"{k}: {' '.join(v)}" for k, v in sorted(unr.items())))


def compare(ctx, a, found, not_under, site_classes):
    """Whether the reading and the site agree: on the class, and on every id the site was asked."""
    if not site_classes:
        on_class = ""
    elif set(site_classes) == set(a.classes):
        on_class = "yes"
    elif set(site_classes) < set(a.classes):
        on_class = "the site states one of the reading's " + str(len(a.classes))
    else:
        on_class = "no"
    bad = [f"{i} found, the reading {a.of(i)[0]}" for i in sorted(found) if a.of(i)[0] != "yes"]
    bad += [f"{i} not found, the reading {a.of(i)[0]}" for i in sorted(not_under) if a.of(i)[0] != "no"]
    on_ids = "" if not (found or not_under) else "yes" if not bad else "no: " + "; ".join(bad)
    return on_class, on_ids


def case_row(ctx, ev, kind, case, realm, base, frame, bestiary, source, broken=frozenset()):
    a = reading(ctx, realm, base, frame, bestiary, broken)
    key = (base, frame, bestiary)
    found = ev.found.get(key, {}) if kind == "captured" else {}
    not_under = ev.not_under.get(base, {}) if kind == "captured" or "the site's word" in case else {}
    site_classes = sorted(ev.klass.get(key, ())) if kind == "captured" else []
    on_class, on_ids = compare(ctx, a, found, not_under, site_classes)
    yes, und, unr = render(ctx, a)
    return [kind, case, realm, base, frame, "yes" if bestiary else "no", " and ".join(a.classes), a.class_open,
            yes, " ".join(i for i in a.yes(ctx) if i not in found), und, a.listed, unr,
            "; ".join(f"{i}: {join(n)}" for i, n in sorted(found.items())),
            "; ".join(f"{i}: {', '.join(n)}" for i, n in sorted(not_under.items())),
            "; ".join(site_classes), on_class, on_ids, "; ".join(a.rests), source]


def ruled_cases(ctx, ev, copy_keys):
    """For each sentence of the paragraph and each ruling, at least one item the captures do not
    hold: base and frame as an item of the copy has them where the copy holds one, else as the
    export names the base (no frame), else constructed and marked so."""
    captured = {k[0] for k in ev.found}
    used = set()
    out = []
    nothing = []
    cache = {k: reading(ctx, "pc", *k) for k in copy_keys}

    def from_copy(pred):
        best = sorted(((-n, k) for k, n in copy_keys.items() if k[0] not in captured and k[0] not in used and pred(k, cache[k])))
        return best[0][1] if best else None

    def from_export(pred):
        names = sorted((len(cs), n) for n, cs in ctx.ex.by_name.items() if n not in captured and n not in used and pred(n, cs))
        return names[0][1] if names else None

    def add(case, key, source, realm="pc"):
        used.add(key[0])
        out.append(("ruled", case, realm, key[0], key[1], key[2], source))

    def leaf_case(case, leaf, internal=None):
        def on_copy(k, a):
            if a.listed != leaf:
                return False
            return internal is None or internal in common.classes_of(ctx.ex, k[0], k[1])[0]
        k = from_copy(on_copy)
        if k:
            return add(case, k, "the copy")

        def in_export(n, cs):
            return any(leaf_of(ctx, c, n, frozenset()) == leaf and (internal is None or c == internal) for c in cs)
        n = from_export(in_export)
        if n:
            return add(case, (n, "", False), "the export's name; no frame")
        nothing.append(leaf)  # every base of the leaf is a captured row already: no row is made up

    # J3 first, so the invitations are not taken by another sentence's pick
    polaric = from_copy(lambda k, a: k[0] == "Polaric Invitation")
    add("J3: every other invitation takes `map` (the site's word is j08's)", polaric or ("Polaric Invitation", "", False),
        "the copy" if polaric else "the export's name; no frame")
    leaf_case("J3: the Maven's Invitation leaf holds a base named for the Maven (not asked)", "map.invitation")
    out.append(("ruled", "J19, V2: an invitation of the quest frame has no id", "pc", "Polaric Invitation", "Quest", False, "constructed: the copy's base, the frame set"))
    out.append(("ruled", "class.rs: an invitation with no frame, its class open among two", "pc", "Polaric Invitation", "", False, "constructed: the copy's base, no frame"))
    # J2: the classes the site puts at a parent, one row a class
    for parent in sorted(ctx.prefix_parents):
        for internal, tid in sorted(ctx.tax.CLASS_TO_TRADE.items()):
            if tid == parent:
                leaf_case(f"J2: `{parent}` matches a class of its own, {ctx.ex.display(internal) or internal} ({internal})", parent, internal)
    # the leaves: a leaf is a class's, or a class's with a rule on the base name; J2's dot and J4's members ride on them
    rule_ids = {fine for _, _, fine in ctx.tax.NAME_RULES}
    for i in ctx.ids:
        if i in ctx.prefix_parents or i in ctx.groupings or i in MONSTER or i == "map.invitation":
            continue
        what = "a class's with a rule on the base name" if i in rule_ids else "a class's"
        extra = ""
        if i.split(".")[0] in ctx.prefix_parents:
            extra = f"; J2: under `{i.split('.')[0]}` by the dot"
        if i in ctx.weapon_leaves:
            extra += "; J4, J12: the groupings over it and not"
        leaf_case(f"C106: the leaf `{i}` is {what}{extra}", i)
    # J1, J9, J10, J11 on a beast the captures do not hold
    unknown = sorted(n for n, (c, _) in ctx.colours.items() if c == "unknown" and n not in captured)
    if unknown:
        add("J1, J9, J10, J15: a beast the colour table marks unknown", (unknown[0], "Rare", True), "the colour table's name; the frame the copy's beasts carry")
    out.append(("ruled", "J1, J15: a beast whose name the colour table lacks", "pc", "A Beast The Table Lacks", "Rare", True, "constructed: no source names such a beast"))
    # J11 where two ids nest, and where they do not
    k = from_copy(lambda k, a: a.listed == "map.breachstone")
    if k:
        add("J11: a breachstone is `map` twice over and listed under its leaf", k, "the copy")
    out.append(("ruled", "J16: two leaves, neither under the other, listed under each", "pc", "Energy Blade", "Rare", False, "constructed: the export's name, the frame set"))
    out.append(("ruled", "class.rs: the frame picks the gem", "pc", "Bone Armour", "Gem", False, "constructed: the export's name, the frame set"))
    out.append(("ruled", "class.rs: the frame picks the body armour", "pc", "Bone Armour", "Rare", False, "constructed: the export's name, the frame set"))
    k = from_copy(lambda k, a: "V1" in a.rests)
    if k:
        add("V1: a blighted map is read past its prefix", k, "the copy")
    # C93 and C105
    k = from_copy(lambda k, a: a.listed == "none")
    if k:
        add("C93, C105: a class with no id is known absence", k, "the copy")
    out.append(("ruled", "C93: a base the class table lacks", "pc", "A Base The Table Lacks", "Normal", False, "constructed: no source names such a base"))
    out.append(("ruled", "C93: an item with no base", "pc", "", "Normal", False, "constructed"))
    out.append(("ruled", "C93, J22: a realm with no table, every id undecided", "poe2", "Chaos Orb", "Currency", False, "constructed: the fixture's base in another realm"))
    out.append(("ruled", "J18: a beast in a realm with no table", "poe2", unknown[0] if unknown else "A Beast", "Rare", True, "constructed"))
    n = from_export(lambda n, cs: sorted(cs) == ["DelveSocketableCurrency", "DelveStackableSocketableCurrency"])
    if n:
        add("J17: a resonator with no frame, its class open among two that give one id", (n, "", False), "constructed: the export's name, no frame")
    k = sorted(n for n, cs in ctx.ex.by_name.items() if sorted(cs) == ["Breachstone", "MiscMapItem"] and n not in captured and n not in used)
    if k:
        add("J21: a breachstone with no frame, `map` holding by J17 and its leaf undecided", (k[0], "", False), "constructed: the export's name, no frame")
    # J13, J14
    n = from_export(lambda n, cs: n != "Growing Wombgift" and all(not ctx.ex.display(c) for c in cs) and any(ctx.tax.CLASS_TO_TRADE.get(c) for c in cs))
    if n:
        add("J13: a graft, whose class the export prints no name for", (n, "", False), "the export's name; no frame")
    out.append(("ruled", "J14, J20: Growing Wombgift is `wombgift`, its class Wombgifts", "pc", "Growing Wombgift", "", False, "the export's name; no frame"))
    return out, nothing


