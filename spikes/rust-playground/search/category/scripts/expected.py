def meta_sets():
    """The three sets of Awakened PoE Trade's parser/meta.ts as ItemCategory strings, and the
    enum; None when the clone is absent."""
    path = os.path.join(common.APT, "renderer", "src", "parser", "meta.ts")
    if not os.path.exists(path):
        return None, None
    common.pinned(common.APT, common.APT_COMMIT)
    meta = open(path).read()
    enum = dict(re.findall(r"^\s+(\w+) = '([^']+)'", meta.split("export enum ItemCategory")[1].split("}")[0], re.M))
    sets = {}
    for name, body in re.findall(r"export const (\w+) = new Set\(\[(.*?)\]\)", meta, re.S):
        members = set()
        for token in re.findall(r"\.\.\.(\w+)|ItemCategory\.(\w+)", body):
            members |= sets[token[0]] if token[0] else {enum[token[1]]}
        sets[name] = members
    return sets, enum


def grouping_members(ctx, ev):
    """One row for each of the seven groupings and each leaf under `weapon`: in or out, and what
    says so - the captures by id, or meta.ts marked not asked (J4), or J12 where nothing places it."""
    # the leaf of a fetched item, by the class its clipboard states (the site's word, not the reading's)
    by_display = collections.defaultdict(set)
    for c in ctx.ex.classes:
        if ctx.ex.display(c):
            by_display[ctx.ex.display(c)].add(c)

    def leaves_of_class(klass, base):
        return {leaf_of(ctx, c, base, frozenset()) for c in by_display.get(klass, ())} - {""}

    cap_in = collections.defaultdict(set)
    for key, cats in ev.found.items():
        for klass in ev.klass.get(key, ()):
            for leaf in leaves_of_class(klass, key[0]):
                for cat, names in cats.items():
                    if cat in ctx.groupings:
                        cap_in[(cat, leaf)].update(names)
    cap_out = collections.defaultdict(list)
    for cat, typ, zero, pairs in ev.zero_cells:
        if cat in ctx.groupings:
            for c in ctx.ex.by_name.get(typ, ()):
                leaf = leaf_of(ctx, c, typ, frozenset())
                if leaf in ctx.weapon_leaves:
                    cap_out[(cat, leaf)].append(f"{zero} beside {join(pairs)}")
    sets, enum = meta_sets()
    apt_cat = collections.defaultdict(set)  # weapon leaf -> the ItemCategory strings its bases carry
    sends = {}
    if sets is not None:
        place, _, cmap, _ = common.apt()
        sends = cmap
        back = collections.defaultdict(set)
        for cat, tid in cmap.items():
            back[tid].add(cat)
        for name, tid in place.items():
            for c in ctx.ex.by_name.get(name, ()):
                leaf = leaf_of(ctx, c, name, frozenset())
                if leaf in ctx.weapon_leaves and tid.startswith("weapon"):
                    apt_cat[leaf] |= back[tid]
    rows, conflicts = [], []
    for g in ctx.groupings:
        for leaf in ctx.weapon_leaves:
            cap = "in" if cap_in.get((g, leaf)) else "out" if cap_out.get((g, leaf)) else ""
            if cap_in.get((g, leaf)) and cap_out.get((g, leaf)):
                conflicts.append((g, leaf, "the captures say both"))
            cap_cite = join(cap_in[(g, leaf)]) if cap == "in" else "; ".join(cap_out.get((g, leaf), []))
            meta, meta_cite = "", ""
            cats = sorted(apt_cat.get(leaf, ()))
            if sets is not None and cats:
                if g in SET_GROUPINGS:
                    inside = [c in sets[SET_GROUPINGS[g]] for c in cats]
                    if all(inside) or not any(inside):
                        meta = "in" if all(inside) else "out"
                        meta_cite = f"{SET_GROUPINGS[g]} {'holds' if meta == 'in' else 'lacks'} {'/'.join(cats)}"
                elif any(sends.get(c) == g for c in cats):
                    meta = "in"
                    meta_cite = f"CATEGORY_TO_TRADE_ID sends {g} for {'/'.join(c for c in cats if sends.get(c) == g)}"
            if cap and meta and cap != meta:
                conflicts.append((g, leaf, f"captures {cap}, meta.ts {meta}"))
            if cap:
                member, said = cap, f"captures: {cap_cite}"
            elif meta:
                member, said = meta, f"meta.ts, not asked (J4): {meta_cite}"
            else:
                member, said = "out", "J12: nothing places it"
            rows.append([g, ctx.text[g], leaf, ctx.text[leaf], member, said,
                         meta_cite if cap and meta else ""])
    common.write_csv("grouping-members.csv", HEADER,
                     ["grouping", "grouping_text", "leaf", "leaf_text", "member", "said_by", "meta_ts_beside_the_capture"], rows)
    return rows, conflicts, sets is None


