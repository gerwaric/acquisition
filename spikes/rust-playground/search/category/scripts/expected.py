class Answer:
    def __init__(self):
        self.classes = []      # the class or classes, as the game prints them
        self.class_open = ""   # why the class is not established, or ''
        self.status = {}       # id -> ("yes" | "undecided" | "unruled", cause or cell); an id absent answers no
        self.all_open = None   # ("undecided" | "unruled", cause or cell) on every id that needs the class
        self.listed = ""       # an id, `none`, `undecided`, or `unruled:<cell>`
        self.rests = []

    def rest(self, *labels):
        for label in labels:
            if label not in self.rests:
                self.rests.append(label)

    def of(self, i):
        if i in self.status:
            return self.status[i]
        if self.all_open and i not in MONSTER:
            return self.all_open
        return ("no", "")

    def yes(self, ctx):
        return [i for i in ctx.ids if self.of(i)[0] == "yes"]

    def undecided(self, ctx):
        return [i for i in ctx.ids if self.of(i)[0] == "undecided"]

    def unruled(self, ctx):
        return [i for i in ctx.ids if self.of(i)[0] == "unruled"]


def leaf_of(ctx, internal, base, broken):
    """A leaf is a class's, or a class's with a rule on the base name (the paragraph, fourth sentence)."""
    if "leaf" in broken:
        return ""
    for c, pred, fine in ctx.tax.NAME_RULES:
        if c != internal or "name:" + fine in broken:
            continue
        if fine == "map.invitation" and "J3" not in broken and not maven(base):
            continue  # J3 overrides the taxonomy's rule ("Invitation" in the name): the Maven's alone
        if fine == "currency.tattoo" and "J23" not in broken and "Tattoo" in base:
            return fine  # J23 overrides the taxonomy's rule (the name begins "Tattoo of "): the word, m01 and m03
        if pred(base):
            return fine
    return ctx.tax.CLASS_TO_TRADE.get(internal, "")


def contains(ctx, a, b):
    """Whether id a holds everything under id b, as the rulings state it: a parent by the dot (J2),
    a grouping over a member leaf (J4), Captured Beast over a colour leaf (J1)."""
    if a in ctx.prefix_parents and b.startswith(a + "."):
        return True
    if a == "monster.beast" and b in COLOUR_LEAF.values():
        return True
    return ctx.members.get((a, b), ("",))[0] == "in"


def ids_of_classes(ctx, internals, base, broken):
    """The ids that answer yes for an item of these classes, and (none since J12) the groupings no row places."""
    yes, open_ = [], []
    for internal in internals:
        leaf = leaf_of(ctx, internal, base, broken)
        if leaf not in ctx.idset:
            continue  # C106: a term names the site's id as spelled; an id the filter lacks is no id
        if leaf in ctx.prefix_parents and "J2-own" in broken:
            continue
        yes.append(leaf)  # J2, first half: the classes the site puts at a parent are the parent's own
        top = leaf.split(".")[0]
        if "." in leaf and top in ctx.prefix_parents and "J2-dot" not in broken:
            yes.append(top)  # J2, second half: every id under it by the dot
        for g in ctx.groupings:  # J4: a grouping is a term over reviewed members
            member, said = ctx.members.get((g, leaf), ("", ""))
            if member in ("in", "out") and (("J4-captures" in broken and said.startswith("captures")) or
                                           ("J4-meta" in broken and said.startswith("meta.ts"))):
                member = "out" if member == "in" else "in"
            if said.startswith("J12") and "J12" in broken:
                member = "in"
            if member == "in":
                yes.append(g)
            elif member == "unruled":
                open_.append(g)
    return list(dict.fromkeys(yes)), list(dict.fromkeys(open_))


def reading(ctx, realm, base, frame, bestiary, broken=frozenset()):
    """From an item's facts to its class, the ids that answer yes, the ids undecided and why, the
    ids unruled, and the id a count lists it under."""
    a = Answer()
    base = base or ""
    # C93, class.rs line 361: the item's realm has no table; the class is undecided with that reason
    if realm not in ctx.realms and "C93-realm" not in broken and not (bestiary and "J18" in broken):
        a.class_open = "the class: no table for the realm"
        a.all_open = ("undecided", a.class_open)  # C93: only the terms that needed the class
        for i in MONSTER:
            # J18: "a beast in a realm with no table is undecided"
            # J22: "in a realm with no table every id is undecided on every item", an item without the line too
            if bestiary or "J22" not in broken:
                a.status[i] = ("undecided", a.class_open)
        a.listed = "undecided"  # C105: a key not established
        a.rest("C93", "J18" if bestiary else "J22")
        return a
    # J1: "A captured beast, known by its bestiary line, is `monster.beast`"
    if bestiary and "J1-line" not in broken:
        a.status["monster.beast"] = ("yes", "")
        a.rest("J1")
        # J9: "A beast's class is the game's own word for it, Stackable Currency, read by the same line"
        if "J9" not in broken:
            a.classes = [BEAST_CLASS]
            a.rest("J9")
        else:
            a.class_open = "the class: base not in the table"
        # J1: "its colour leaf is the row of the colour table"
        colour = "unknown" if "J1-colour" in broken else ctx.colours.get(base, ("absent", ""))[0]
        if colour in COLOUR_LEAF:
            a.status[COLOUR_LEAF[colour]] = ("yes", "")
        elif "J1-unknown" not in broken:
            # J1: "a name the table lacks or marks unknown being undecided with that reason"
            why = ("the colour: the colour table lacks the name" if colour == "absent"
                   else "the colour: the colour table marks the name unknown")
            for leaf in COLOUR_LEAF.values():
                a.status[leaf] = ("undecided", why)
        # J10: "That class gives a beast no id: ... never `currency`"
        if "J10" in broken:
            for i in ids_of_classes(ctx, [BEAST_CLASS_INTERNAL], base, broken)[0]:
                a.status[i] = ("yes", "")
        else:
            a.rest("J10")
        # J11: "A count by category lists an item under its most specific id"
        a.rest("J11")
        if "J11" in broken:
            a.listed = "monster.beast"
        elif colour in COLOUR_LEAF:
            a.listed = COLOUR_LEAF[colour]
        elif "J15" in broken:
            a.listed = "undecided"
        else:
            # J15: "a count lists a beast of undecided colour under `monster.beast`"
            a.listed = "monster.beast"
            a.rest("J15")
        return a
    # C93, class.rs line 372: the item has no base
    if not base:
        a.class_open = "the class: no base"
        a.all_open = ("undecided", a.class_open)
        a.listed = "undecided"
        a.rest("C93")
        return a
    # the class as common.py reads it: the base exact, else past a blight prefix (V1)
    internals, how = common.classes_of(ctx.ex, base, None)
    if "prefix" in how:
        a.rest("V1")
        if "V1-blight" in broken:
            internals = set()
    # C93, class.rs line 392: the base is not in the table
    if not internals:
        a.class_open = "the class: base not in the table"
        a.all_open = ("undecided", a.class_open)
        a.listed = "undecided"
        a.rest("C93")
        return a
    display = {c: ctx.ex.display(c) for c in internals}
    named = sorted(c for c in internals if display[c])
    # J14: "Growing Wombgift is `wombgift`" - the site's list over the export's class, a rule on that one base name
    if base == "Growing Wombgift" and "J14" not in broken:
        a.rest("J14")
        if "J20" in broken:
            a.status["wombgift"] = ("yes", "")
            a.class_open = "the class: the export prints no name for the base's class"
            a.all_open = ("undecided", a.class_open)
            a.listed = "wombgift"
            return a
        # J20: "Growing Wombgift's class is Wombgifts, the item as any wombgift is" - read on as one
        internals = {c for c, t in ctx.tax.CLASS_TO_TRADE.items() if t == "wombgift"}
        display = {c: ctx.ex.display(c) for c in internals}
        named = sorted(c for c in internals if display[c])
        a.rest("J20")
    # J13: "a base whose class the export prints no name for (the grafts) is undecided"
    if not named and "J13" not in broken:
        a.class_open = "the class: the export prints no name for the base's class"
        a.all_open = ("undecided", a.class_open)
        a.listed = "undecided"
        a.rest("J13", "C93")
        return a
    if not named:  # J13 broken: the export's class answers
        yes, _ = ids_of_classes(ctx, sorted(internals), base, broken)
        for i in yes:
            a.status[i] = ("yes", "")
        a.listed = yes[-1] if yes else "none"
        return a
    names = sorted({display[c] for c in named})
    among = ""
    if len(names) > 1:
        # class.rs lines 414-464: the frame picks among the candidates, and the item is each that remains
        a.rest("class.rs (the frame picks)")
        if not frame or "frame" in broken:
            among = "the class: base under several classes"
        else:
            f = frame.lower()
            if f == "gem":
                picked = [n for n in names if n in common.GEM_CLASSES]
            elif f == "quest":
                picked = [n for n in names if n == common.QUEST_CLASS]
            else:
                picked = [n for n in names if n not in common.GEM_CLASSES and n != common.QUEST_CLASS]
            if not picked:
                among = "the class: base under several classes"
            else:
                mirror, _ = common.classes_of(ctx.ex, base, frame)
                assert {display[c] for c in mirror if display[c]} == set(picked), (base, frame)
                names = picked
    if among:
        # class.rs (F2): what stays open keeps its candidates; a term false under every candidate is false
        a.class_open = among
        a.rest("C93")
        per = [set(ids_of_classes(ctx, [c for c in named if display[c] == n], base, broken)[0]) for n in names]
        for i in ctx.ids:
            n = sum(1 for p in per if i in p)
            if n == len(per) and "J17" not in broken:
                a.status[i] = ("yes", "")  # J17: "an id every candidate class gives holds while the class is open"
                a.rest("J17")
            elif n:
                a.status[i] = ("undecided", among)
        yes = a.yes(ctx)
        if not yes:
            a.listed = "undecided"
        else:
            most = [y for y in yes if not any(contains(ctx, y, z) for z in yes if z != y)]
            below = [u for u in a.undecided(ctx) if any(contains(ctx, y, u) for y in yes)]
            if below and "J21" in broken:
                a.listed = "undecided"
            else:
                # J21: "a count lists an item whose class is open under the most specific id that holds"
                a.listed = " ".join(most)  # J11, and J16 where two are not nested
                a.rest("J21" if below else "J11")
        return a
    if len(names) > 1 and "all" in broken:
        names = names[:1]
    a.classes = names
    picked_internal = [c for c in named if display[c] in names]
    yes, open_ = ids_of_classes(ctx, picked_internal, base, broken)
    a.rest("C106 (a leaf is a class's)")
    if any(leaf_of(ctx, c, base, frozenset()) != ctx.tax.CLASS_TO_TRADE.get(c, "") for c in picked_internal):
        a.rest("C106 (a rule on the base name)")
    if any(c == "MiscMapItem" for c in picked_internal) and "Invitation" in base:
        a.rest("J3")
    for i in yes:
        a.status[i] = ("yes", "")
    assert not open_, "J12: every cell of data/grouping-members.csv is in or out"
    if any(i in ctx.prefix_parents for i in yes):
        a.rest("J2")
    if any(i in ctx.groupings for i in yes) or any(leaf.startswith("weapon.") for leaf in yes):
        a.rest("J4")
    # J19: "a quest-frame invitation has no id" - its class, Quest Items (V2), decides, over J3's letter
    if "Invitation" in base and names == [common.QUEST_CLASS] and "MiscMapItem" in internals:
        a.rest("J19", "V2")
        if "J19" in broken:
            yes = ids_of_classes(ctx, ["MiscMapItem"], base, broken)[0]
            for i in yes:
                a.status[i] = ("yes", "")
    if not yes:
        # C105: "Known absence is `none`" - the class is established and has no id
        a.rest("C105")
        if "C105-none" in broken:
            a.all_open = ("undecided", "the class has no id")
            a.listed = "undecided"
        else:
            a.listed = "none"
        return a
    # J11: "A count by category lists an item under its most specific id"
    a.rest("J11")
    if "J11" in broken:
        least = [y for y in yes if not any(contains(ctx, z, y) for z in yes if z != y)]
        a.listed = least[0]
    else:
        most = [y for y in yes if not any(contains(ctx, y, z) for z in yes if z != y)]
        if len(most) > 1:
            a.rest("J16")  # J16: "an item of two leaves not nested is listed under each"
        a.listed = most[0] if len(most) == 1 else "undecided" if "J16" in broken else " ".join(most)
    return a


