def category_of(query):
    c = (((query.get("filters") or {}).get("type_filters") or {}).get("filters") or {}).get("category")
    return (c or {}).get("option") or ""


def prune(node):
    if isinstance(node, dict):
        out = {k: prune(v) for k, v in node.items()}
        return {k: v for k, v in out.items() if v not in ({}, [], None)}
    if isinstance(node, list):
        return [prune(v) for v in node]
    return node


def without_category(query):
    q = json.loads(json.dumps(bare(query)))
    ((((q.get("filters") or {}).get("type_filters") or {}).get("filters")) or {}).pop("category", None)
    return json.dumps(prune(q), sort_keys=True)


def raw_items(path):
    """[(baseType, frameTypeId, bestiary line?, Item Class)] of a raw fetch, or None when it is absent.
    Nothing else of an item is read."""
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        return None
    out = []
    for r in json.load(open(path)).get("result") or []:
        it = r.get("item") or {}
        t = (it.get("extended") or {}).get("text")
        first = base64.b64decode(t).decode("utf-8", "replace").split("\n")[0].rstrip("\r") if t else ""
        klass = first[len("Item Class: "):] if first.startswith("Item Class: ") else ""
        out.append((common.shown(it.get("baseType")), it.get("frameTypeId") or "", it.get("descrText") == common.BEAST_HELP, klass))
    return out


class Evidence:
    """What the site said: per (base, frame, bestiary line) the ids it was found under and the class its
    clipboard states; per base the ids a search of its type found nothing under beside a pair that found it."""

    def __init__(self):
        self.found = collections.defaultdict(lambda: collections.defaultdict(list))
        self.klass = collections.defaultdict(collections.Counter)
        self.not_under = collections.defaultdict(lambda: collections.defaultdict(list))
        self.tally = collections.Counter()
        self.left = collections.defaultdict(list)
        self.absent = []
        self.zero_cells = []  # (category, type, zero, pairs)

    def load(self):
        captures = json.load(open(EXTRACT))["searches"] if os.path.exists(EXTRACT) else None
        if captures is None:
            self.absent.append("../pseudo-stats/data/captures.json")
            captures = {}
        by_rest = collections.defaultdict(list)
        for name, c in captures.items():
            if c["search"].get("total"):
                by_rest[without_category(c["returned_query"])].append(name)
        named = {n: c for n, c in captures.items() if category_of(c["returned_query"])}
        self.tally["the extract: captures whose query names a category"] = len(named)
        raw_missing = []
        for name in sorted(named, key=natural):
            c = named[name]
            q = c["returned_query"]
            cat, typ, total = category_of(q), q.get("type") or "", c["search"].get("total") or 0
            if total == 0:
                pairs = [p for p in by_rest.get(without_category(q), []) if p != name]
                if not typ:
                    self.left["found nothing and names no type: a zero is read only of a type"].append(name)
                elif not pairs:
                    self.left["found nothing beside no capture that found the type: says nothing"].append(name)
                else:
                    self.not_under[typ][cat].append(f"{name} beside {join(pairs)}")
                    self.zero_cells.append((cat, typ, name, pairs))
                    self.tally["read: found nothing beside a pair that found the type"] += 1
                continue
            if not c.get("fetched"):
                self.left["found items and no fetch was kept"].append(name)
                continue
            items = raw_items(os.path.join(RAW, f"{name}-fetch.json"))
            if items is None:
                raw_missing.append(name)
                self.left["the raw fetch is absent (the frame and the bestiary line are read from it)"].append(name)
                continue
            if len(items) != len(c["fetched"]):
                self.left["the raw fetch and the extract hold different numbers of items"].append(name)
                continue
            self.tally["read: items fetched"] += 1
            for base, frame, beast, klass in items:
                self.found[(base, frame, beast)][cat].append(name)
                if klass:
                    self.klass[(base, frame, beast)][klass] += 1
        if raw_missing:
            self.absent.append(f"../pseudo-stats/raw/searches: {len(raw_missing)} fetches")
        # the 2026-09-13 fetches common.site_fetches reads (trade-query), by the same four facts
        reqs = sorted(glob.glob(os.path.join(common.TQ_FETCHES, "*-request.json")), key=lambda p: natural(os.path.basename(p)[:-13]))
        if not reqs:
            self.absent.append("../trade-query/raw/searches")
        for req in reqs:
            name = os.path.basename(req)[: -len("-request.json")]
            try:
                cat = category_of(json.load(open(req)).get("query") or {})
            except ValueError:
                cat = ""
            if not cat:
                continue
            self.tally["the 2026-09-13 fetches: requests whose query names a category"] += 1
            items = raw_items(os.path.join(common.TQ_FETCHES, name + "-fetch.json"))
            if not items:
                self.left["a 2026-09-13 request with no fetch"].append(name)
                continue
            self.tally["read: items fetched"] += 1
            for base, frame, beast, klass in items:
                self.found[(base, frame, beast)][cat].append(name)
                if klass:
                    self.klass[(base, frame, beast)][klass] += 1


