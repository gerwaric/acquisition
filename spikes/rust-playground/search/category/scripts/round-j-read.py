#!/usr/bin/env python3
"""category, round j read: what each captured search of round j found.

    python3 search/category/scripts/round-j-read.py

Reads search/pseudo-stats/data/captures.json (the committed, scrubbed extract, tools/trade-captures.py)
for each captured j row: the site's total, whether it is inexact, the ids returned, and of the
fetched items their base types, rarities and, for a beast, the lure and mods readings (the
export's lure words; the count of its bestiary mods among the item's explicitMods, as
scripts/beasts.py reads the copy; the counts are written beside the reading, which names no colour
for a count over 2). The extract keeps no clipboard text, so the `Item Class:`
line is read from the raw fetches (search/pseudo-stats/raw/searches/<row>-fetch.json, local,
MANIFEST.md of pseudo-stats): only that line, nothing about a seller. When a captured row's raw
fetch is absent the run prints the reading and writes nothing, so the file is never written
with a column another machine would fill differently.

Each row is read beside its pair: the rows its sheet control names (`jNN`, `jNN–jMM`). A pair
both of whose captured sides found nothing is printed as such: the type has no listing and
the pair says nothing. For the one such pair of page 1 (j12, j13) the replacement scarab is
chosen here and printed: of the export's bases the shipped rule places at `map.scarab`, those
on the site's coarse `map` list, the one the copy holds most (ties by name).

Inputs (read-only): the extract and raw fetches above, the sheet
(../pseudo-stats/data/search-sheet.csv), poe1/data @ e2bd511a, the site's coarse list, the copy
(sqlite mode=ro). Output (data/): round-j-read.csv, one row per captured search of round j.
"""

import base64
import collections
import csv
import json
import os
import re
import sys

sys.dont_write_bytecode = True  # nothing is cached beside a script this track does not own
import common  # noqa: E402

PS = os.path.join(common.SEARCH, "pseudo-stats")
EXTRACT = os.path.join(PS, "data", "captures.json")
RAW = os.path.join(PS, "raw", "searches")
SHEET = os.path.join(PS, "data", "search-sheet.csv")
HEADER = ("# generated by scripts/round-j-read.py from ../pseudo-stats/data/captures.json (totals, items), "
          "../pseudo-stats/raw/searches/j*-fetch.json (local; the clipboard's Item Class line only), "
          "poe1/data @ e2bd511a (base_items, mods)")


def fmt(counter):
    return "; ".join(f"{k}:{v}" for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], str(kv[0]))))


def named(control):
    out = []
    for a, b in re.findall(r"j(\d+)(?:[–-]j(\d+))?", control):
        out += [f"j{i:02d}" for i in range(int(a), int(b or a) + 1)]
    return out


def item_classes(row):
    """Counter of the clipboard's Item Class line over the raw fetch, or None when it is absent."""
    path = os.path.join(RAW, f"{row}-fetch.json")
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        return None
    out = collections.Counter()
    for r in json.load(open(path)).get("result") or []:
        t = ((r.get("item") or {}).get("extended") or {}).get("text")
        first = base64.b64decode(t).decode("utf-8", "replace").split("\n")[0].rstrip("\r") if t else ""
        out[first[len("Item Class: "):] if first.startswith("Item Class: ") else "(no clipboard)"] += 1
    return out


def main():
    ex = common.Export()
    lures = {b["name"][: -len(" Lure")] for b in ex.bases.values() if b["name"] and b["name"].endswith(" Lure")}
    bestiary = {m["name"] for m in ex.mods.values() if m.get("generation_type") == "bestiary" and m.get("name")}
    captures = json.load(open(EXTRACT))["searches"]
    with open(SHEET, newline="") as fh:
        sheet = {r["search"]: r for r in csv.DictReader(fh) if re.fullmatch(r"j\d+", r["search"])}
    rows, missing_raw = [], []
    pending = sorted(n for n in sheet if n not in captures)
    total = {}
    for name in sorted(n for n in captures if re.fullmatch(r"j\d+", n)):
        c = captures[name]
        q = c["returned_query"]
        cat = (((q.get("filters") or {}).get("type_filters") or {}).get("filters") or {}).get("category", {}).get("option", "")
        items = c.get("fetched") or []
        total[name] = c["search"]["total"]
        beast = [i for i in items if (i.get("properties") or []) and [p[1] for p in i["properties"]] == ["Genus", "Group", "Family"]]
        lure = collections.Counter("red" if i["baseType"].split(" ")[0] in lures else "yellow" for i in beast)
        counts = collections.Counter(sum(1 for m in (i.get("lines") or {}).get("explicitMods") or []
                                         if m.get("description") in bestiary) for i in beast)
        mods = collections.Counter()
        for k, v in counts.items():
            mods[{1: "yellow", 2: "red"}.get(k, "none")] += v
        classes = item_classes(name) if items else collections.Counter()
        if classes is None:
            missing_raw.append(name)
            classes = collections.Counter()
        rows.append([name, cat or "(none)", q.get("type", "") or "(none)", c["search"]["total"],
                     "yes" if c["search"].get("inexact") else "no", c["ids_returned"], len(items),
                     fmt(collections.Counter(i["baseType"] for i in items)), fmt(classes),
                     fmt(collections.Counter(i.get("rarity") for i in items)),
                     fmt(lure) if beast else "", fmt(counts) if beast else "", fmt(mods) if beast else ""])
    # a row's pair: the rows its control names and the rows whose control names it, of the same type
    # when the row has one (j01–j06 name each other across two types; j07 and j33 have none)
    types = {r[0]: r[2] for r in rows}
    sheet_type = {n: json.loads(sheet[n]["query"]).get("type", "") or "(none)" for n in sheet}
    for r in rows:
        linked = set(named(sheet[r[0]]["control"])) | {n for n in sheet if r[0] in named(sheet[n]["control"])}
        linked.discard(r[0])
        if types[r[0]] != "(none)":
            linked = {n for n in linked if sheet_type[n] == types[r[0]]}
        r.append(" ".join(sorted(linked)))
    print(f"round j captured: {len(rows)} of {len(sheet)} rows; not yet: {len(pending)} ({pending[0]}–{pending[-1]})")
    print(f"to sit: {len(pending)} searches, {len(pending) * 10 // 60} min {len(pending) * 10 % 60} s at one link every 10 s "
          f"(tools/trade-pages.py's PACE), {-(-len(pending) // 25)} page(s) of 25")
    for r in rows:
        print(f"  {r[0]}  {r[1]:<20} {r[2]:<24} total {r[3]}{' (inexact)' if r[4] == 'yes' else ''}; fetched {r[6]}: {r[7] or '-'}"
              f"{'; class ' + r[8] if r[8] else ''}{'; lure ' + r[10] + ', bestiary mods ' + r[11] + ', mods ' + r[12] if r[10] else ''}; pair {r[13]}")
    dead = []
    for r in rows:
        pair = [n for n in r[13].split() if n in total]
        if r[3] == 0 and pair and all(total[n] == 0 for n in pair):
            dead.append(r[0])
    print(f"captured rows that found nothing beside a captured pair that found nothing: {dead or 'none'}")
    zero_read = [(r[0], [n for n in r[13].split() if total.get(n)]) for r in rows if r[3] == 0 and r[0] not in dead]
    print(f"captured rows that found nothing beside a pair that found the type: {zero_read}")
    # the replacement scarab for j12/j13
    tax = common.taxonomy()
    coarse, _ = common.site_coarse()
    held = collections.Counter(common.shown(b.get("baseType")) for _, _, _, b in common.copy_items() or [])
    scarabs = sorted({n for n, cs in ex.by_name.items() if any(tax.predict(c, n)[0] == "map.scarab" for c in cs)
                      and "map" in coarse.get(n, ())}, key=lambda n: (-held[n], n))
    print(f"scarab bases at map.scarab by the rule, on the site's map list: {len(scarabs)}; held on the copy: "
          f"{sum(1 for n in scarabs if held[n])}; the most held: {[(n, held[n]) for n in scarabs[:3]]}")
    if missing_raw:
        print(f"raw fetches absent for {missing_raw}: data/round-j-read.csv not written")
        return 1
    common.write_csv("round-j-read.csv", HEADER,
                     ["search", "category", "type", "total", "inexact", "ids_returned", "fetched", "fetched_base_types",
                      "item_class", "rarities", "beast_lure_reading", "beast_bestiary_mod_counts", "beast_mods_reading", "pair"], rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())
