# ---------------------------------------------------------------- page parsing


def visible(fragment):
    fragment = re.sub(r"(?s)<br\s*/?>", " ", fragment)
    fragment = re.sub(r"(?s)<[^>]+>", " ", fragment)
    return " ".join(html.unescape(fragment).split())


def parse_entries(segment):
    entries = []
    starts = [m.start() for m in re.finditer(r'<div class="item-filter-document-body">', segment)]
    starts.append(len(segment))
    for a, b in zip(starts, starts[1:]):
        chunk = segment[a:b]
        ribbon = re.search(r'class="corner-ribbon[^"]*">([^<]*)<', chunk)
        name = re.search(r'class="item-filter-document-name">(.*?)</div>', chunk, re.S)
        desc = re.search(r'class="item-filter-document-description[^"]*">(.*?)$', chunk, re.S)
        body = desc.group(1) if desc else ""
        lead = re.split(r"<div class=", body, maxsplit=1)[0]
        values = re.search(r">Values\s*</h5>(.*?)</div>", body, re.S)
        pres = re.findall(r"<pre>(.*?)</pre>", body, re.S)
        entries.append(
            {
                "ribbon": visible(ribbon.group(1)) if ribbon else "",
                "name": visible(name.group(1)) if name else "",
                "description": visible(lead),
                "values": visible(values.group(1)) if values else "",
                "example": " ; ".join(" ".join(html.unescape(p).split()) for p in pres),
            }
        )
    return entries


def sections(page):
    body = re.sub(r"(?is)<script.*?</script>", "", page)
    body = re.sub(r"(?is)<style.*?</style>", "", body)
    titles = [
        (m.start(), visible(m.group(1)))
        for m in re.finditer(r'class="item-filter-document-title"[^>]*>(.*?)</h[34]>', body, re.S)
    ]
    bounds = {}
    for i, (pos, title) in enumerate(titles):
        end = titles[i + 1][0] if i + 1 < len(titles) else len(body)
        bounds[title] = (pos, end)
    return body, bounds


