OPERATORS = {
    "cmp": "= ! != < <= > >= ==",
    "eq": "= ! != ==",
}


def main():
    page = open(PAGE, encoding="utf-8", errors="replace").read()
    body, bounds = sections(page)

    a, b = bounds["Conditions"]
    conditions = parse_entries(body[a:b])
    actions = []
    for title in ("Drop Sound", "Other Actions"):
        a, b = bounds[title]
        for e in parse_entries(body[a:b]):
            actions.append((e["name"], title))

    # ---- validate the hand join against the sibling extracts
    cpp = tomllib.load(open(CPP, "rb"))
    captions = {f["caption"] for f in cpp["filter"]}
    grammar = json.load(open(GRAMMAR))
    trade_ids = {f["id"] for g in grammar["filter_groups"] for f in g["filters"]}
    stats = json.load(open(STATS))
    stat_ids = {e["id"] for g in stats["result"] for e in g["entries"]}
    stat_prefixes = {g["id"] for g in stats["result"]}
    fields = set()
    with open(FIELDS) as fh:
        for row in csv.DictReader(line for line in fh if not line.startswith("#")):
            fields.add(row["path"])

    names = [c["name"] for c in conditions]
    problems = []
    if set(names) != set(JOIN):
        problems.append(f"page conditions != hand join: {set(names) ^ set(JOIN)}")
    for name, (_t, _o, field, cppf, tradef, _n) in JOIN.items():
        if cppf and cppf not in captions:
            problems.append(f"{name}: cpp_filter {cppf!r} is not a caption in filters.toml")
        if tradef:
            if tradef.startswith("stat:"):
                sid = tradef[5:]
                ok = sid in stat_ids or (sid.endswith(".*") and sid[:-2] in stat_prefixes)
                if not ok:
                    problems.append(f"{name}: trade stat {sid!r} unknown")
            elif tradef.startswith("query."):
                if tradef[6:] not in grammar["query_shape"]:
                    problems.append(f"{name}: query shape key {tradef!r} unknown")
            elif tradef not in trade_ids:
                problems.append(f"{name}: trade_filter {tradef!r} is not a filter id in grammar.json")
        for tok in field.split(";"):
            tok = tok.strip()
            for alt in tok.split("|"):
                if alt.startswith(("absent:", "derived:", "base-data:")) or not alt:
                    continue
                if alt not in fields:
                    problems.append(f"{name}: item_field {alt!r} is not a path in field-census.csv")
    if problems:
        for p in problems:
            print("FAIL:", p, file=sys.stderr)
        return 1

    os.makedirs(os.path.dirname(OUT_C), exist_ok=True)
    with open(OUT_C, "w", newline="") as fh:
        fh.write(HEADER_C + "\n")
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(
            [
                "condition", "ribbon", "operand_type", "operators", "values", "example",
                "item_field", "cpp_filter", "trade_filter", "notes",
            ]
        )
        for c in conditions:
            t, o, field, cppf, tradef, note = JOIN[c["name"]]
            w.writerow(
                [
                    c["name"], c["ribbon"], t, OPERATORS[o], c["values"], c["example"],
                    field, cppf, tradef, note,
                ]
            )

    with open(OUT_A, "w", newline="") as fh:
        fh.write(HEADER_A + "\n")
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["action", "section"])
        for name, section in actions:
            w.writerow([name, section])

    print(f"conditions: {len(conditions)}  actions: {len(actions)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
